/** The icons an extension may name in its manifest (EXTENSION_ICONS in @aura/shared). */
const ICONS: Record<ExtensionIcon, LucideIcon> = {
  blocks: Blocks,
  bell: Bell,
  "book-open": BookOpen,
  bot: Bot,
  bug: Bug,
  calendar: Calendar,
  "chart-bar": ChartBar,
  "chart-line": ChartLine,
  "check-square": SquareCheck,
  "clipboard-list": ClipboardList,
  clock: Clock,
  cloud: Cloud,
  code: Code,
  database: Database,
  "file-text": FileText,
  folder: Folder,
  gauge: Gauge,
  "git-branch": GitBranch,
  globe: Globe,
  "heart-pulse": HeartPulse,
  inbox: Inbox,
  kanban: Kanban,
  "layout-dashboard": LayoutDashboard,
  "list-todo": ListTodo,
  mail: Mail,
  map: MapIcon,
  megaphone: Megaphone,
  "notebook-pen": NotebookPen,
  package: Package,
  rocket: Rocket,
  search: Search,
  server: Server,
  shield: Shield,
  "shopping-cart": ShoppingCart,
  "sticky-note": StickyNote,
  table: Table,
  terminal: Terminal,
  ticket: Ticket,
  users: Users,
  wallet: Wallet,
  wrench: Wrench,
  zap: Zap,
};

export function extensionIcon(icon: ExtensionIcon | null): LucideIcon {
  return (icon && ICONS[icon]) || Blocks;
}
